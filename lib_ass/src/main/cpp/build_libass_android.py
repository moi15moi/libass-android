import os
import shutil
import subprocess
import sys
import tomllib
from argparse import ArgumentParser
from dataclasses import dataclass
from enum import Enum, auto
from pathlib import Path
from platform import system
from textwrap import dedent


@dataclass(frozen=True)
class Target:
    """Android ABI target and cross-compilation metadata.

    Attributes:
        abi: Android ABI name (ex: "arm64-v8a", "armeabi-v7a"). From https://developer.android.com/ndk/guides/other_build_systems
        triple: LLVM target triple (ex: "aarch64-linux-android"). From https://developer.android.com/ndk/guides/other_build_systems
        meson_cpu: Meson cpu value for host_machine.
        meson_cpu_family: Meson cpu_family value for host_machine. From https://mesonbuild.com/Reference-tables.html#cpu-families
    """

    abi: str
    triple: str
    meson_cpu: str
    meson_cpu_family: str


class BuildSystem(Enum):
    """Build system used by a project."""

    MESON = auto()
    AUTOTOOLS = auto()


@dataclass
class Project:
    """Description of a dependency or project to build.

    Attributes:
        name: Project name (ex: for lib path resolution).
        source_dir: Source directory of the project, inside its git submodule (ex: third_party/libass).
        build_system: Build system used by the project.
        additional_build_flags: Flags passed to configure/meson for all ABIs.
        additional_build_flags_for_abi: Per-ABI flags (ex: --enable-asm for x86_64).
        is_shared: If True, build a shared library (.so). Otherwise build a static library (.a).
        autogen_script: Autotools only. Script that generates the configure script from a git checkout.
        autogen_output: Autotools only. File generated by autogen_script, relative to source_dir.
            If it exists, autogen_script doesn't need to run again.
    """

    name: str
    source_dir: Path
    build_system: BuildSystem
    additional_build_flags: list[str]
    additional_build_flags_for_abi: dict[Target, list[str]]
    is_shared: bool
    autogen_script: str = "autogen.sh"
    autogen_output: str = "configure"


@dataclass
class ToolchainBuildEnv:
    """Variables for the NDK toolchain."""

    CC: str
    CXX: str
    AR: str
    LD: str
    NM: str
    RANLIB: str
    STRIP: str
    LDFLAGS: str
    PREFIX: str
    PKG_CONFIG_LIBDIR: str


def meson_string(value: str) -> str:
    """Quote a value as a Meson string literal, for the cross file.

    Meson reads backslash escapes in strings (ex: \\U in C:\\Users), and a ' ends the string,
    so both are escaped.

    Parameters:
        value: Value to quote.

    Returns:
        The value between single quotes, with backslashes and single quotes escaped.
    """
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def create_meson_cross_file(target: Target, toolchain_build_env: ToolchainBuildEnv, build_dir: Path) -> Path:
    """Generate the Meson cross-compilation file of an ABI target.

    Parameters:
        target: Android ABI target (arm64-v8a, armeabi-v7a, x86, x86-64).
        toolchain_build_env: NDK toolchain paths.
        build_dir: Directory where the cross file is written.

    Returns:
        Path to the Meson cross file (build_dir/meson-cross-{abi}.txt).
    """
    meson_cross_file_content = dedent(f"""
    [built-in options]
    prefix = {meson_string(toolchain_build_env.PREFIX)}
    wrap_mode = 'nodownload'
    c_link_args = {meson_string(toolchain_build_env.LDFLAGS)}
    cpp_link_args = {meson_string(toolchain_build_env.LDFLAGS)}

    [binaries]
    c = {meson_string(toolchain_build_env.CC)}
    cpp = {meson_string(toolchain_build_env.CXX)}
    c_ld = {meson_string(toolchain_build_env.LD)}
    cpp_ld = {meson_string(toolchain_build_env.LD)}
    ar = {meson_string(toolchain_build_env.AR)}
    nm = {meson_string(toolchain_build_env.NM)}
    ranlib = {meson_string(toolchain_build_env.RANLIB)}
    strip = {meson_string(toolchain_build_env.STRIP)}
    pkg-config = 'pkg-config'

    [host_machine]
    system = 'android'
    cpu_family = {meson_string(target.meson_cpu_family)}
    cpu = {meson_string(target.meson_cpu)}
    endian = 'little'

    [properties]
    pkg_config_libdir = {meson_string(toolchain_build_env.PKG_CONFIG_LIBDIR)}
    """)

    # The file is only rewritten when its content changes, because Meson
    # reconfigures the build when the cross file is modified.
    meson_cross_file = build_dir.joinpath(f"meson-cross-{target.abi}.txt")
    if not meson_cross_file.is_file() or meson_cross_file.read_text(encoding="utf-8") != meson_cross_file_content:
        meson_cross_file.write_text(meson_cross_file_content, encoding="utf-8")

    return meson_cross_file


def prepare_autotools_env(toolchain_build_env: ToolchainBuildEnv, debug: bool) -> dict[str, str]:
    """Build an environment dict with NDK toolchain variables for Autotools builds.

    Parameters:
        toolchain_build_env: NDK toolchain paths.
        debug: If True, build without optimizations and with debug info.

    Returns:
        A copy of the current environment with the toolchain variables set.
    """
    env = os.environ.copy()
    env.update({
        "CC": toolchain_build_env.CC,
        "CXX": toolchain_build_env.CXX,
        "AR": toolchain_build_env.AR,
        "LD": toolchain_build_env.LD,
        "NM": toolchain_build_env.NM,
        "RANLIB": toolchain_build_env.RANLIB,
        "STRIP": toolchain_build_env.STRIP,
        "LDFLAGS": toolchain_build_env.LDFLAGS,
        "PKG_CONFIG_LIBDIR": toolchain_build_env.PKG_CONFIG_LIBDIR,
    })

    if debug:
        env["CFLAGS"] = "-g -O0"
        env["CXXFLAGS"] = "-g -O0"

    return env


def read_gradle_versions(repo_root: Path) -> tuple[int, str]:
    """Read minSdk and ndkVersion from the Gradle version catalog.

    Gradle and this script share these values so the prebuilt libraries are
    always built against the same API level and NDK as the rest of the project.

    Parameters:
        repo_root: Root of the repository.

    Returns:
        (minSdk, ndkVersion)
    """
    catalog_path = repo_root.joinpath("gradle", "libs.versions.toml")
    with catalog_path.open("rb") as f:
        versions = tomllib.load(f)["versions"]
    return int(versions["minSdk"]), str(versions["ndkVersion"])


def ensure_ndk_installed(sdk_path: Path, ndk_version: str, repo_root: Path) -> Path:
    """Return the NDK path, installing it if it is missing.

    The NDK is installed with the :lib_ass:installNdk Gradle task
    (the Android Gradle Plugin downloads ndkVersion if it is missing).

    Parameters:
        sdk_path: Path to the Android SDK.
        ndk_version: NDK version to install (ex: 28.1.13356709).
        repo_root: Root of the repository, where gradlew is.

    Returns:
        Path to the NDK (sdk_path/ndk/{ndk_version}).
    """
    ndk_path = sdk_path.joinpath("ndk", ndk_version)
    if ndk_path.is_dir():
        return ndk_path

    gradlew = repo_root.joinpath("gradlew.bat" if system() == "Windows" else "gradlew")
    print(f"=== Installing NDK {ndk_version} with Gradle ===")
    # Gradle uses sdk.dir from local.properties first, then ANDROID_HOME.
    env = os.environ.copy()
    env["ANDROID_HOME"] = str(sdk_path)
    subprocess.run(
        [str(gradlew), ":lib_ass:installNdk"],
        cwd=repo_root,
        check=True,
        env=env,
        encoding="utf-8",
    )

    if not ndk_path.is_dir():
        raise NotADirectoryError(
            f"Gradle finished, but \"{ndk_path}\" still doesn't exist. "
            "Check that sdk.dir in local.properties points to the same SDK as --sdk-path."
        )
    return ndk_path


def get_toolchain_path(ndk_path: Path) -> Path:
    """Resolve the NDK LLVM toolchain path for the current host OS.

    Parameters:
        ndk_path: Root path of the Android NDK installation.
            (ex: .../ndk/27.0.12077973)

    Returns:
        Path to the prebuilt LLVM toolchain (toolchains/llvm/prebuilt/{os}).
        The OS variant is derived from the current platform:
        windows-x86_64, linux-x86_64, or darwin-x86_64.
    """
    system_name = system()

    # See NDK OS Variant in https://developer.android.com/ndk/guides/other_build_systems#overview
    if system_name == "Windows":
        # We don't really support Windows cause autotools doesn't work on Windows.
        os_name = "windows-x86_64"
    elif system_name == "Linux":
        os_name = "linux-x86_64"
    elif system_name == "Darwin":
        os_name = "darwin-x86_64"
    else:
        raise NotImplementedError(f"The system {system_name} isn't supported.")

    toolchain_path = ndk_path.joinpath("toolchains", "llvm", "prebuilt", os_name)
    if not toolchain_path.is_dir():
        raise NotADirectoryError(f"The toolchain \"{toolchain_path.absolute()}\" doesn't exist")

    return toolchain_path


def bootstrap_project(project: Project, reconfigure: bool) -> None:
    """Check that the project's submodule is checked out and prepare it for building.

    Parameters:
        project: Project to prepare.
        reconfigure: If True, generate the configure script even if it already exists.
    """
    if project.build_system == BuildSystem.AUTOTOOLS and (
        reconfigure or not project.source_dir.joinpath(project.autogen_output).is_file()
    ):
        print(f"=== Generating the configure script of {project.name} ===")
        # NOCONFIGURE stops some autogen.sh scripts (ex: libunibreak) from also running configure.
        env = os.environ.copy()
        env["NOCONFIGURE"] = "1"
        subprocess.run([f"./{project.autogen_script}"], cwd=project.source_dir, check=True, env=env, encoding="utf-8")


def build_project(
    project: Project,
    target: Target,
    toolchain_build_env: ToolchainBuildEnv,
    meson_cross_file: Path,
    build_dir: Path,
    reconfigure: bool,
    debug: bool,
) -> None:
    """Build a project for the given ABI target.

    The build directory is kept between runs, so only the changed files are recompiled.
    meson setup and ./configure only run if the build directory isn't configured yet or if reconfigure is True.
    So if the compiler (NDK, minSdk) or a configure option changes, reconfigure must be True.

    Debug and release builds use different build directories, so switching between them doesn't need reconfigure.
    Both install to the same prefix (build_dir/{abi}), so the last build is the one used.

    Parameters:
        project: Project to build.
        target: Android ABI target (arm64-v8a, armeabi-v7a, x86, x86-64).
        toolchain_build_env: NDK toolchain paths of the target.
        meson_cross_file: Meson cross file of the target (see create_meson_cross_file).
        build_dir: Root directory for builds.
        reconfigure: If True, run meson setup or ./configure even if the build directory is already configured.
        debug: If True, build without optimizations and with debug info.
    """
    build_type = "debug" if debug else "release"
    print(f"=== Building {project.name} for {target.abi} ({build_type}) ===")

    project_build_dir = build_dir.joinpath(f"{project.name}-{target.abi}-{build_type}")
    build_flags = project.additional_build_flags + project.additional_build_flags_for_abi.get(target, [])

    if project.build_system == BuildSystem.MESON:
        default_library = "shared" if project.is_shared else "static"

        is_configured = project_build_dir.joinpath("meson-private", "coredata.dat").is_file()
        if reconfigure or not is_configured:
            subprocess.run(
                [
                    "meson",
                    "setup",
                    str(project_build_dir),
                    str(project.source_dir),
                    "--cross-file", str(meson_cross_file),
                    f"--buildtype={build_type}",
                    f"--default-library={default_library}",
                ] + build_flags + (["--reconfigure"] if is_configured else []),
                check=True,
                encoding="utf-8"
            )

        subprocess.run(["meson", "compile", "-C", str(project_build_dir)], check=True, encoding="utf-8")
        subprocess.run(["meson", "install", "-C", str(project_build_dir)], check=True, encoding="utf-8")
    elif project.build_system == BuildSystem.AUTOTOOLS:
        env_autotools = prepare_autotools_env(toolchain_build_env, debug)
        project_build_dir.mkdir(exist_ok=True)

        if project.is_shared:
            default_library = ["--enable-shared", "--disable-static"]
        else:
            default_library = ["--enable-static", "--disable-shared"]

        is_configured = project_build_dir.joinpath("config.status").is_file()
        if reconfigure or not is_configured:
            subprocess.run(
                [
                    str(project.source_dir.joinpath("configure")),
                    f"--host={target.triple}",
                    f"--prefix={toolchain_build_env.PREFIX}",
                    "--with-pic",
                ] + build_flags + default_library,
                cwd=project_build_dir,
                check=True,
                env=env_autotools,
                encoding="utf-8"
            )

        jobs = f"-j{os.cpu_count() or 1}"
        subprocess.run(["make", jobs], cwd=project_build_dir, check=True, env=env_autotools, encoding="utf-8")
        subprocess.run(["make", jobs, "install"], cwd=project_build_dir, check=True, env=env_autotools, encoding="utf-8")
    else:
        raise ValueError(f"The build system {project.build_system} isn't implemented.")


def main() -> None:
    # When stdout isn't a terminal (ex: github actions), print() output is buffered,
    # while subprocesses (Gradle, meson, make) write directly to stdout.
    # Flush at every newline so the messages of this script appear in order with the subprocess output.
    sys.stdout.reconfigure(line_buffering=True)

    parser = ArgumentParser(description="Build libass for android")
    parser.add_argument(
        "--sdk-path",
        type=Path,
        required=True,
        help="""
    The Android SDK path. Ex: C:\\Users\\moi15moi\\AppData\\Local\\Android\\Sdk
    """,
    )

    parser.add_argument(
        "--reconfigure",
        action="store_true",
        help="""
    Run autogen, meson setup and ./configure again for every project, even if they are already configured.
    Without it, they only run when a build directory isn't configured yet.
    Use it when the compiler (NDK version, minSdk) or a configure/meson option changes.
    """,
    )

    parser.add_argument(
        "--debug",
        action="store_true",
        help="""
    Build the libraries without optimizations and with debug info (-O0 -g), to debug them.
    Debug and release builds have separate build directories, so switching doesn't need --reconfigure.
    """,
    )

    args = parser.parse_args()
    sdk_path: Path = args.sdk_path
    need_reconfigure: bool = args.reconfigure
    is_debug_build: bool = args.debug

    python_file_path = Path(__file__).resolve()
    repo_root = python_file_path.parent.parent.parent.parent.parent
    api_level, ndk_version = read_gradle_versions(repo_root)

    if not sdk_path.is_dir():
        raise NotADirectoryError(f"The Android SDK path \"{sdk_path.absolute()}\" doesn't exist")

    ndk_path = ensure_ndk_installed(sdk_path, ndk_version, repo_root)
    toolchain_path = get_toolchain_path(ndk_path)

    third_party_dir = python_file_path.parent.joinpath("third_party")

    build_dir = python_file_path.parent.joinpath("build_native_lib")
    build_dir.mkdir(exist_ok=True)

    target_arm = Target("armeabi-v7a", "armv7a-linux-androideabi", "armv7a", "arm")
    target_aarch64 = Target("arm64-v8a", "aarch64-linux-android", "aarch64", "aarch64")
    target_x86 = Target("x86", "i686-linux-android", "i686", "x86")
    target_x86_64 = Target("x86_64", "x86_64-linux-android", "x86_64", "x86_64")

    targets = [
        target_arm,
        target_aarch64,
        target_x86,
        target_x86_64
    ]

    projects = [
        Project("harfbuzz", third_party_dir.joinpath("harfbuzz"), BuildSystem.MESON, ["-Dtests=disabled", "-Ddocs=disabled", "-Dutilities=disabled", "-Draster=disabled", "-Dvector=disabled", "-Dgpu=disabled", "-Dsubset=disabled", "-Dfreetype=disabled", "-Dzlib=disabled"], {}, True),
        Project("freetype", third_party_dir.joinpath("freetype"), BuildSystem.AUTOTOOLS, ["--with-harfbuzz=yes", "--with-zlib=no"], {}, True, autogen_output="builds/unix/configure"),
        Project("fribidi", third_party_dir.joinpath("fribidi"), BuildSystem.MESON, ["-Ddocs=false", "-Dtests=false"], {}, True),
        Project("unibreak", third_party_dir.joinpath("unibreak"), BuildSystem.AUTOTOOLS, [], {}, True),
        Project("expat", third_party_dir.joinpath("expat", "expat"), BuildSystem.AUTOTOOLS, ["--without-tests", "--without-docbook"], {}, True, autogen_script="buildconf.sh"),
        Project("fontconfig", third_party_dir.joinpath("fontconfig"), BuildSystem.MESON, ["-Dtests=disabled", "-Ddoc=disabled", "-Dtools=disabled", "-Dxml-backend=expat"], {}, True),
        Project("ass", third_party_dir.joinpath("libass"), BuildSystem.AUTOTOOLS, ["--enable-fontconfig", "--enable-libunibreak"], {target_aarch64: ["--enable-asm"], target_x86: ["--enable-asm"], target_x86_64: ["--enable-asm"]}, True),
    ]

    for project in projects:
        bootstrap_project(project, need_reconfigure)

    for target in targets:
        prefix_dir = build_dir.joinpath(target.abi)
        if prefix_dir.is_dir():
            shutil.rmtree(prefix_dir)
        prefix_dir.mkdir()

        # See https://developer.android.com/ndk/guides/other_build_systems#autoconf
        toolchain_build_env = ToolchainBuildEnv(
            str(toolchain_path.joinpath("bin", f'{target.triple}{api_level}-clang')),
            str(toolchain_path.joinpath("bin", f'{target.triple}{api_level}-clang++')),
            str(toolchain_path.joinpath("bin", "llvm-ar")),
            str(toolchain_path.joinpath("bin", "ld")),
            str(toolchain_path.joinpath("bin", "llvm-nm")),
            str(toolchain_path.joinpath("bin", "llvm-ranlib")),
            str(toolchain_path.joinpath("bin", "llvm-strip")),
            "-Wl,-z,max-page-size=16384", # Android require 16 KB page sizes: https://developer.android.com/guide/practices/page-sizes
            str(prefix_dir),
            str(prefix_dir.joinpath("lib", "pkgconfig"))
        )
        meson_cross_file = create_meson_cross_file(target, toolchain_build_env, build_dir)

        for project in projects:
            build_project(project, target, toolchain_build_env, meson_cross_file, build_dir, need_reconfigure, is_debug_build)

    # The prefab package "ass" (see lib_ass/build.gradle.kts) exposes a single headers directory,
    # not one per ABI. The installed headers are the same for every ABI, so take them from the first one.
    include_dir = build_dir.joinpath("include")
    if include_dir.exists():
        shutil.rmtree(include_dir)
    shutil.copytree(build_dir.joinpath(targets[0].abi, "include"), include_dir)


if __name__ == "__main__":
    main()
